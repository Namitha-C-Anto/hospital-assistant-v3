def build_summary(
    test_data: list[dict], 
    pipeline_results: list[PipelineResults], 
    ragas_time: float, 
    df: pd.DataFrame, 
) -> dict:
    
    """
    Build a summary of the RAG pipeline and RAGAS evaluation results.

    The summary combines execution statistics, retrieval statistics,
    token usage, and average RAGAS metric scores into a single
    dictionary for reporting and analysis.

    Args:
        test_data: Original test dataset.
        pipeline_results: Results generated by the RAG pipeline.
        ragas_time: Total time taken to run the RAGAS evaluation.
        df: DataFrame containing the RAGAS evaluation results.

    Returns:
        Dictionary containing the experiment summary.
    """

    if not pipeline_results:
        raise RuntimeError("No successful test cases were collected.")

    num_questions = len(pipeline_results)

    # -------------------------------------------------
    # Build the overall experiment summary
    # -------------------------------------------------
    summary = {
        "total_questions": len(test_data),
        "successful_questions": num_questions,
        "failed_questions": len(test_data) - num_questions,
        "ragas_evaluation_seconds": ragas_time,
    }

    # -------------------------------------------------
    # Add pipeline execution statistics
    # -------------------------------------------------
    summary.update(build_latency_summary(pipeline_results, num_questions))
    summary.update(build_chunk_summary(pipeline_results, num_questions))
    summary.update(build_token_summary(pipeline_results, num_questions))

    # -------------------------------------------------
    # Add average RAGAS metric scores
    # -------------------------------------------------
    summary.update(build_ragas_summary(df))

    return summary