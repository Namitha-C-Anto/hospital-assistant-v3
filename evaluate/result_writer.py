import json
import os
from dataclasses import asdict
from typing import Any
import pandas as pd
from pathlib import Path

from config import (
    RAGAS_RESULTS_PATH, 
    DATASET, 
    TEMPERATURE, 
    EVALUATION_PATH,)
from utils.logger import logger
from rag.models import PipelineResults

def add_metadata(
    df: pd.DataFrame, 
    metadata: dict[str, Any],
)-> pd.DataFrame:
    """
    Add experiment metadata as columns to the evaluation DataFrame.

    Each metadata value is assigned to every row so that the exported
    evaluation results include the configuration used to produce them.

    Args:
        df: DataFrame containing the evaluation results.
        metadata: Dictionary containing the experiment configuration.

    Returns:
        DataFrame with the metadata columns added.
    """

    for key, value in metadata.items():
        df[key] = value

    return df

#---------------------------------------------------------------------
def get_results_output_path (
    metadata  : dict[str, Any]
) -> Path:
    """
    Generate the output path for the experiment results.

    The output directory is created if it does not already exist.

    Args:
        metadata: Experiment configuration metadata.

    Returns:
        Full path to the JSON results file.
    """

    # -------------------------------------------------
    # Ensure the output directory exists
    # -------------------------------------------------
    output_dir = RAGAS_RESULTS_PATH 
    output_dir.mkdir(parents=True, exist_ok=True)

    # -------------------------------------------------
    # Build the output file path
    # -------------------------------------------------
    return output_dir / f"{metadata['experiment']}.json"

#---------------------------------------------------------------------Summary
def save_summary_csv(
    summary : dict[str, Any], 
    metadata : dict[str, Any],
) -> None:

    """
    Save the experiment summary to the master summary CSV.

    If the master experiment summary CSV already exists, the new experiment is appended.
    Otherwise, a new summary file is created.

    Args:
        summary: Aggregated experiment statistics.
        metadata: Experiment configuration metadata.
    """

    # -------------------------------------------------
    # Combine experiment metadata and summary statistics
    # -------------------------------------------------
    summary_row = {
        **metadata, 
        **summary,
    }
     
    summary_path = Path(EVALUATION_PATH) / "experiment_summary.csv"
    summary_df = pd.DataFrame([summary_row])
    
    # -------------------------------------------------
    # Append to the existing summary file if available
    # -------------------------------------------------
    if summary_path.exists:

        existing_df = pd.read_csv(summary_path)

        summary_df = pd.concat(
            [existing_df, summary_df],
            ignore_index=True,
        )

    # -------------------------------------------------
    # Save the updated experiment summary
    # -------------------------------------------------
   
    logger.info("Saving experiment summary to '%s'.", summary_path)

    summary_df.to_csv(
        summary_path, 
        index=False,
    )
    
    logger.info("Saving experiment summary to '%s'.", summary_path)
    logger.info("Experiment summary saved successfully.")

#-------------------------------------------------------------JSON
def save_json_results(
    output_path: Path,
    metadata: dict[str, Any],
    summary: dict[str, Any],
    test_data: list[dict[str, Any]],
    pipeline_results: list[PipelineResults],
) -> None:
    
    """
    Save the complete experiment results as a JSON file.

    The JSON contains the experiment configuration, summary statistics,
    run statistics, and the detailed results for each test question.

    Args:
        output_path: Destination path for the JSON file.
        metadata: Experiment configuration metadata.
        summary: Aggregated experiment statistics.
        test_data: Original test dataset.
        pipeline_results: Results generated by the RAG pipeline.
    """

    # -------------------------------------------------
    # Build the JSON output structure
    # -------------------------------------------------
    json_data = {
        "version": "1.0",
        "experiment": metadata,
        "summary": summary,
        "run_statistics": {
            "total_questions": len(test_data),
            "successful_questions": len(pipeline_results),
            "failed_questions": len(test_data) - len(pipeline_results),
        },
        "results": [
            asdict(result)
            for result in pipeline_results
        ],
    }

    # -------------------------------------------------
    # Save the JSON results
    # -------------------------------------------------
    with open(output_path, "w", encoding="utf-8") as file:
        json.dump(
            json_data,
            file,
            indent=4,
            ensure_ascii=False,
        )
    logger.info(
        "JSON results saved successfully to '%s'. "
        "Saved %d successful results.",
        output_path,
        len(pipeline_results),
    )

#-------------------------------------------------------------------
def save_results(
    metadata: dict[str, Any],
    summary: dict[str, Any],
    test_data: list[dict[str, Any]],
    pipeline_results: list[PipelineResults],
) -> None:

    """
    Save the experiment results and summary to disk.

    This function coordinates the output generation by saving the
    experiment summary and the detailed JSON results.

    Args:
        metadata: Experiment configuration metadata.
        summary: Aggregated experiment statistics.
        test_data: Original test dataset.
        pipeline_results: Results generated by the RAG pipeline.
    """

    # -------------------------------------------------
    # Save the experiment summary
    # -------------------------------------------------
    save_summary_csv(
        summary, 
        metadata,
    )
    
    # -------------------------------------------------
    # Generate the output path for this experiment
    # -------------------------------------------------
    output_path = get_results_output_path(metadata)
    
    # -------------------------------------------------
    # Save the complete experiment results
    # -------------------------------------------------
    save_json_results(
        output_path, 
        metadata, 
        summary, 
        test_data, 
        pipeline_results,
    )